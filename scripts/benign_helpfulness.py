def verify(run, models=False):
    manifest, cfg = read_json(run/"manifest.json"), read_json(run/"config.json")
    validate_config(cfg)
    groups = [(run/n, h) for n, h in manifest["files"].items()]
    groups += [(path(n), h) for field in ("sources", "external_input_sha256") for n, h in manifest[field].items()]
    if models: groups += [(path(n), h) for n, h in manifest["external_model_sha256"].items()]
    for filename, expected in groups:
        if stream_hash(filename) != expected: raise ValueError("immutable Phase A source/input/model changed")
    for name, version in manifest["packages"].items():
        if importlib.metadata.version(name) != version: raise ValueError("runtime package changed")
    return cfg, manifest


def registration(args, run):
    cfg, manifest = verify(run)
    if not args.registration: raise ValueError("exact committed Phase A registration required")
    for name in (*SOURCES, cfg["protocol"], cfg["fixture_acceptance"], args.registration): committed(name)
    record = read_json(args.registration)
    if record.get("manifest_sha256") != stream_hash(run/"manifest.json"):
        raise ValueError("registered run manifest differs")
    return cfg, manifest


def resource_check(cfg):
    value = subprocess.run(["nvidia-smi", "--id=0", "--query-gpu=uuid,name,driver_version,memory.free,utilization.gpu",
        "--format=csv,noheader,nounits"], capture_output=True, text=True, check=True, shell=False).stdout.strip().split(",")
    uuid, name, driver, free, utilization = [s.strip() for s in value]
    if uuid != cfg["gpu_uuid"] or int(free) < cfg["minimum_free_mib"] or int(utilization) > cfg["maximum_utilization_percent"]:
        raise RuntimeError("GPU identity/resources incompatible; stop without touching jobs or changing settings")
    return {"physical_gpu": "0", "gpu_uuid": uuid, "name": name, "driver": driver,
            "free_mib_before_load": int(free), "utilization_percent_before_load": int(utilization)}



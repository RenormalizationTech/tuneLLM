def normalize(text):
    return " ".join(unicodedata.normalize("NFKC", text).casefold().split())


def validate_fixture(fixture, phase):
    rows = fixture["items"]
    if fixture["phase"] != phase or len(rows) != 36 or Counter(r["family"] for r in rows) != Counter({f: 4 for f in FAMILIES}):
        raise ValueError("fixture must have36 rows, four per registered family, in its declared phase")
    if len({r["id"] for r in rows}) != 36 or len({normalize(r["user"]) for r in rows}) != 36:
        raise ValueError("duplicate IDs or normalized prompts")
    for row in rows:
        if (row["class"] != ("physics" if row["family"].startswith("physics_") else "sensitive") or
                not row["user"].strip() or not row["legitimacy_note"].strip() or
                not isinstance(row["anchors"], list) or len(row["anchors"]) != 3 or
                any(not isinstance(a, str) or not a.strip() for a in row["anchors"]) or
                len(set(row["anchors"])) != 3 or "system" in row):
            raise ValueError("three distinct anchors, legitimacy and baseline-only fixture required")
    return rows


def historical_safe():
    """Read only safe rows/prompts; never copy historic response text or unsafe rows."""
    files = [f"evaluation/tone/{p}.json" for p in ("extraction", "development", "final")]
    files += ["evaluation/small_tasks.json", "data/refusal-01/prepared/extraction.json",
              "data/refusal-01/prepared/development.json", "data/refusal-01/prepared/final.json"]
    files += [f"data/benchmark-screen-01/{p}.json" for p in
              ("development", "test", "writing_development", "writing_test", "writing_development_fewshot", "writing_test_fewshot")]
    prompts, hashes = [], {}
    def collect(value):
        if isinstance(value, dict):
            for key, child in value.items():
                if key in ("user", "instruction", "prompt") and isinstance(child, str): prompts.append(child)
                elif key == "messages":
                    prompts.extend(m["content"] for m in child if m["role"] == "user")
                elif isinstance(child, (dict, list)): collect(child)
        elif isinstance(value, list):
            for child in value: collect(child)
    for name in files:
        data = read_json(name)
        if name.endswith("prepared/extraction.json"): data = [r["benign"] for r in data["pairs"]]
        elif "/prepared/" in name: data = [r for r in data["items"] if r["label"] == "safe"]
        collect(data)
        hashes[name] = stream_hash(path(name))
    csv_file = path("data/refusal-01/raw/xstest_prompts.csv")
    with csv_file.open(encoding="utf-8", newline="") as stream:
        prompts.extend(row["prompt"] for row in csv.DictReader(stream) if row["label"] == "safe")
    hashes[str(csv_file)] = stream_hash(csv_file)
    return {normalize(p) for p in prompts}, hashes


def fixture_check(cfg):
    dev = validate_fixture(read_json(cfg["fixture"]), "development")
    heldout = validate_fixture(read_json(cfg["heldout_fixture"]), "heldout")
    historic, hashes = historical_safe()
    if {r["id"] for r in dev} & {r["id"] for r in heldout}:
        raise ValueError("development/heldout IDs overlap")
    dev_text, held_text = ({normalize(r["user"]) for r in rows} for rows in (dev, heldout))
    if dev_text & held_text or historic & (dev_text | held_text):
        raise ValueError("normalized development/heldout/historical safe prompt overlap")
    seal = read_json(cfg["heldout_manifest"])
    for phase, rows, name in (("development", dev, cfg["fixture"]), ("heldout", heldout, cfg["heldout_fixture"])):
        expected = {"sha256": stream_hash(path(name)), "ids": [r["id"] for r in rows],
            "family_counts": dict(Counter(r["family"] for r in rows)), "class_counts": dict(Counter(r["class"] for r in rows))}
        if seal[phase] != expected:
            raise ValueError("fixture bytes/IDs/counts differ from pre-output heldout seal")
    return {"normalized_historical_safe_prompts": len(historic), "exact_normalized_overlap": 0,
            "semantic_novelty_established_by_duplicate_check": False, "seal": seal}, hashes


